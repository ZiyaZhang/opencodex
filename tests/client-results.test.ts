import assert from 'node:assert/strict';
import test from 'node:test';
import { createElement } from 'react';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { OpenCodexPage, PluginResultSummary, ScreenshotUpload } from '../src/client/page.js';
import type { Artifact, Candidate, Job, Verification } from '../src/core/types.js';
import type { OpenCodexRequest, OpenCodexResponse } from '../src/host/remote.js';

const artifact: Artifact = { id: 'package', jobId: 'job', path: 'job/plugin.tgz', kind: 'plugin', label: 'Generated question plugin', bytes: 2000, sha256: 'a'.repeat(64), createdAt: '2026-10-14T00:00:00Z', provenance: { kind: 'operator-assisted', details: 'Generated by the model; manually repaired and packaged.' } };
const job = { id: 'job', status: 'paused', artifactId: 'package' } as Job;
const call = async () => ({} as OpenCodexResponse);

test('a paused job with a package exposes an experimental download and assisted provenance', async () => {
  let renderer!: ReactTestRenderer;
  await act(async () => { renderer = create(createElement(PluginResultSummary, { job, artifacts: [artifact], checks: [], call })); });
  const content = JSON.stringify(renderer.toJSON());
  assert.match(content, /下载实验包/); assert.match(content, /人工协助产物/);
  assert.match(content, /当前未处于验收阶段/); assert.match(content, /Generated by the model/);
  assert.doesNotMatch(content, /尚未产出插件包/);
  await act(async () => renderer.unmount());
});

test('output summary distinguishes missing packages and excludes verification for another hash or specification', async () => {
  const check = { id: 'check', jobId: job.id, artifactId: artifact.id, artifactSha256: artifact.sha256, specId: 'old-spec', scope: 'behavior', outcome: 'passed' } as Verification;
  let renderer!: ReactTestRenderer;
  await act(async () => { renderer = create(createElement(PluginResultSummary, { job, artifacts: [], checks: [], call })); });
  assert.match(JSON.stringify(renderer.toJSON()), /尚未产出插件包/);
  await act(async () => { renderer.update(createElement(PluginResultSummary, { job, artifacts: [artifact], checks: [check], latestSpecId: 'latest-spec', call })); });
  const labels = renderer.root.findByProps({ 'aria-label': '插件验收状态' }).findAllByType('span').map(node => node.children.filter(child => typeof child === 'string').join(''));
  assert.deepEqual(labels, ['行为 · 待验收', '视觉 · 待验收', '生命周期 · 待验收']);
  await act(async () => renderer.unmount());
});

test('adding a DSH screenshot records user provenance and a visible caption without starting research', async () => {
  const original = Object.getOwnPropertyDescriptor(globalThis, 'FileReader');
  class Reader {
    result = 'data:image/png;base64,aW1hZ2UtYnl0ZXM=';
    onload?: () => void;
    readAsDataURL() { this.onload?.(); }
  }
  Object.defineProperty(globalThis, 'FileReader', { configurable: true, value: Reader });
  let renderer!: ReactTestRenderer;
  const requests: OpenCodexRequest[] = [];
  try {
    await act(async () => { renderer = create(createElement(ScreenshotUpload, { job, busy: false, run: async request => { requests.push(request); return {} as OpenCodexResponse; } })); });
    await act(async () => renderer.root.findByType('select').props.onChange({ target: { value: 'dsh' } }));
    const captionInput = renderer.root.findAllByType('input').find(node => node.props.maxLength === 1000)!;
    await act(async () => captionInput.props.onChange({ target: { value: 'Question card and composer appear together' } }));
    await act(async () => renderer.root.findByProps({ type: 'file' }).props.onChange({ currentTarget: { files: [new File(['bytes'], 'dsh.png', { type: 'image/png' })] } }));
    assert.equal(renderer.root.findByType('img').props.alt, '待添加的截图预览');
    await act(async () => renderer.root.findByType('form').props.onSubmit({ preventDefault() {} }));
    assert.deepEqual(requests, [{ action: 'addScreenshot', jobId: job.id, image: { mimeType: 'image/png', dataBase64: 'aW1hZ2UtYnl0ZXM=' }, metadata: { subject: 'dsh', caption: 'Question card and composer appear together', provenance: 'user' } }]);
    assert.equal(renderer.root.findAllByType('img').length, 0);
  } finally {
    if (renderer) await act(async () => renderer.unmount());
    if (original) Object.defineProperty(globalThis, 'FileReader', original); else delete (globalThis as Record<string, unknown>).FileReader;
  }
});

function candidate(id: string, sourceType: Candidate['sourceType']): Candidate {
  return { id, title: `feature-${id}`, description: 'A concrete public feature', sourceUrl: 'https://example.test/update', detectedAt: '2026-10-14T00:00:00Z', updatedAt: '2026-10-14T00:00:00Z', fingerprint: id, status: 'new', sourceType };
}
function emptyState(): OpenCodexResponse['state'] {
  return { schemaVersion: 1, createdAt: '', updatedAt: '', settings: { defaultJobTokenLimit: 120000, dailyTokenLimit: 300000, maxDurationMs: 3600000, maxRepairRounds: 3, monitorEnabled: false, monitorIntervalMinutes: 360, localVersionFile: '', updateResearchMode: 'notify' }, candidates: [], jobs: [], artifacts: [], evidence: [], specs: [], verifications: [], reservations: [], capabilities: null };
}

test('discovery source failures are errors, not a successful zero-result scan', async () => {
  let scan: OpenCodexResponse['scan'] = { baseline: 0, changed: 0, unchanged: 0, discovered: 0, errors: ['Official source is unavailable'] };
  const call = async (request: OpenCodexRequest) => ({ state: emptyState(), budgets: {}, ...(request.action === 'scan' ? { scan } : {}) });
  let renderer!: ReactTestRenderer;
  try {
    await act(async () => { renderer = create(createElement(OpenCodexPage, { call })); });
    await act(async () => renderer.root.findByType('nav').findAllByType('button')[1].props.onClick());
    await act(async () => renderer.root.findByProps({ className: 'oc-section-head' }).findByType('button').props.onClick());
    assert.match(JSON.stringify(renderer.root.findByProps({ role: 'alert' }).children), /检查失败/);
    assert.doesNotMatch(JSON.stringify(renderer.toJSON()), /检查完成/);
    scan = { baseline: 1, changed: 0, unchanged: 0, discovered: 2, errors: ['Another source is unavailable'] };
    await act(async () => renderer.root.findByProps({ className: 'oc-section-head' }).findByType('button').props.onClick());
    assert.match(JSON.stringify(renderer.root.findByProps({ role: 'alert' }).children), /部分来源检查失败/);
    assert.match(JSON.stringify(renderer.root.findByProps({ role: 'status' }).children), /已保存 2 项功能候选/);
  } finally { if (renderer) await act(async () => renderer.unmount()); }
});

test('discovery selects feature entries in a batch and creates drafts without starting research or selecting version signals', async () => {
  const requests: OpenCodexRequest[] = [];
  const state = { ...emptyState(), candidates: [candidate('a', 'public-source'), candidate('b', 'public-source'), candidate('version', 'local-version')] };
  const call = async (request: OpenCodexRequest) => {
    requests.push(request);
    if (request.action === 'create') state.candidates = state.candidates.map(item => item.id === request.input.candidateId ? { ...item, status: 'selected' } : item);
    return { state: { ...state }, budgets: {} };
  };
  let renderer!: ReactTestRenderer;
  try {
    await act(async () => { renderer = create(createElement(OpenCodexPage, { call })); });
    const discovery = renderer.root.findAllByType('nav')[0].findAllByType('button')[1];
    await act(async () => discovery.props.onClick());
    const selectAll = renderer.root.findAllByType('input').find(node => node.props.type === 'checkbox')!;
    await act(async () => selectAll.props.onChange({ target: { checked: true } }));
    const batch = renderer.root.findByProps({ className: 'oc-discovery-actions' }).findByType('button');
    await act(async () => { batch.props.onClick(); });
    assert.deepEqual(requests.filter(request => request.action === 'create').map(request => request.input.candidateId), ['a', 'b']);
    assert.equal(requests.some(request => request.action === 'start'), false);
    assert.match(JSON.stringify(renderer.toJSON()), /已创建 2 项研究任务/);
  } finally { if (renderer) await act(async () => renderer.unmount()); }
});
