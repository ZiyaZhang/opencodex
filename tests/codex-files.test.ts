/** A protocol file as ts-rs writes it: two header lines, the `import type` lines, one single-line type. */
const tsFile = (name: string, fields: string[], imports: string[] = [], generator = GENERATOR): string =>
  `${GENERATED}\n\n${generator}\n${imports.map(i => `import type { ${i} } from "./${i}";\n`).join('')}\nexport type ${name} = { ${fields.join(', ')}, };\n`;
