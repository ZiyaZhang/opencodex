test('the excerpt ends at a whole line and a count of the lines left out, within the cap; one line longer than the cap is cut with an ellipsis', () => {
  const lines = Array.from({ length: 300 }, (_, i) => `line ${i} ${'x'.repeat(30)}`);
  const [many] = groupWatchedFiles([{ path: 'docs/a.md', status: 'added', added: lines }]);
  const shown = many!.excerpt.split('\n');
  const count = shown.pop();
  assert.ok(many!.excerpt.length <= 6_000);
  assert.ok(shown.length > 100 && shown.length < 300, `shown ${shown.length} lines`);
  assert.deepEqual(shown, lines.slice(0, shown.length).map(line => `a.md: ${line}`));
  assert.equal(count, `…另有 ${300 - shown.length} 行`);
  // One more line would not leave room for the count: the count is part of the cap.
  assert.ok(many!.excerpt.length > 6_000 - 60);

  const [huge] = groupWatchedFiles([{ path: 'docs/b.md', status: 'added', added: ['y'.repeat(10_000)] }]);
  assert.equal(huge!.excerpt.length, 6_000);
  assert.ok(huge!.excerpt.startsWith('b.md: yyyy') && huge!.excerpt.endsWith('…'));
  const [hugeFirst] = groupWatchedFiles([{ path: 'docs/c.md', status: 'added', added: ['y'.repeat(10_000), 'second'] }]);
  assert.ok(hugeFirst!.excerpt.length <= 6_000 && hugeFirst!.excerpt.startsWith('c.md: yyyy') && hugeFirst!.excerpt.endsWith('…\n…另有 1 行'));

  // The cut never leaves half of a surrogate pair behind.
  const [emoji] = groupWatchedFiles([{ path: 'docs/d.md', status: 'added', added: ['😀'.repeat(5_000)] }]);
  assert.ok(emoji!.excerpt.length <= 6_000);
  assert.ok(!/[\ud800-\udbff](?![\udc00-\udfff])|(?<![\ud800-\udbff])[\udc00-\udfff]/.test(emoji!.excerpt));
});

