// --- collectFileChanges: a temp-dir store and a stub GitHub client, no network ---

type FilesGitHub = Pick<GitHubClient, 'stableTags' | 'treePaths' | 'fileAt'>;
const TAGS = ['rust-v0.162.1', 'rust-v0.162.0', 'rust-v0.161.0'];
const windowOf = (from: string, to: string): StableWindow => ({ from, to, releases: [to] });
/** With the checkpoint `withStore` presets and these tags, the window is 0.162.0 to 0.162.1. */
const WINDOW = windowOf('rust-v0.162.0', 'rust-v0.162.1');
/** The link of an evidence entry: GitHub's compare page with the anchor of the file. */
const urlOf = (window: StableWindow, path: string): string => `https://github.com/openai/codex/compare/${window.from}...${window.to}#diff-${createHash('sha256').update(path).digest('hex')}`;
/** Nothing was left unread. */
const NONE = { overBudget: 0, rateLimited: 0, failed: 0 };
const OVER_BUDGET = '超出本次读取上限';
const RATE_LIMITED = '已达 GitHub 速率限制';
const isAbortError = (error: unknown) => (error as Error).name === 'AbortError';
const RESET = new Date('2026-10-15T07:30:00Z');
const rateLimit = (path: string, rateLimitResetAt?: Date) => new GitHubError(`GitHub HTTP 403 for repos/openai/codex/contents/${path}: API rate limit exceeded`, `repos/openai/codex/contents/${path}`, { status: 403, rateLimited: true, rateLimitResetAt });

/**
 * `trees` holds the watched blobs of each tag and `texts` the file bodies by `tag:path`; `state.tags` is the stable tag list, newest first.
 * `calls` records every request in order; `failing` makes `fileAt` throw the given value for a path.
 */
function stubGitHub(trees: Record<string, Map<string, string>>, texts: Record<string, string>, tags: string[] = TAGS) {
  const state = { tags: [...tags] };
  const calls = { stableTags: [] as number[], treePaths: [] as string[], fileAt: [] as string[] };
  const failing = new Map<string, unknown>();
  const github: FilesGitHub = {
    stableTags: async limit => { calls.stableTags.push(limit); return state.tags.slice(0, limit); },
    treePaths: async (tag, keep) => {
      calls.treePaths.push(tag);
      const tree = trees[tag];
      if (!tree) throw new Error(`no tree for ${tag}`);
      return new Map([...tree].filter(([path]) => keep(path)));
    },
    fileAt: async (tag, path) => {
      calls.fileAt.push(`${tag}:${path}`);
      if (failing.has(path)) throw failing.get(path);
      const text = texts[`${tag}:${path}`];
      if (text === undefined) throw new Error(`no text for ${tag}:${path}`);
      return text;
    },
  };
  return { github, state, calls, failing };
}

