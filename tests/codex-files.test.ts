/** Two patch windows over `docs/skills.md`: 0.161.0 to 0.162.0, then 0.162.0 to 0.162.1, then 0.162.1 to 0.162.2. `texts` gives the file at each tag. */
function skillsAcrossReleases(texts: Record<string, string>) {
  const sha = (tag: string) => new Map([['docs/skills.md', `sha:${tag}`]]);
  const tags = ['rust-v0.161.0', 'rust-v0.162.0', 'rust-v0.162.1', 'rust-v0.162.2'];
  const stub = stubGitHub(
    Object.fromEntries(tags.map(tag => [tag, sha(tag)])),
    Object.fromEntries(Object.entries(texts).map(([tag, text]) => [`rust-v${tag}:docs/skills.md`, text])),
    ['rust-v0.162.0', 'rust-v0.161.0'],
  );
  const release = (tag: string) => stub.state.tags.unshift(tag);
  return { ...stub, release };
}
const FIRST = windowOf('rust-v0.161.0', 'rust-v0.162.0'), SECOND = windowOf('rust-v0.162.0', 'rust-v0.162.1'), THIRD = windowOf('rust-v0.162.1', 'rust-v0.162.2');

