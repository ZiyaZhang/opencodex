/** A store whose clock advances one second per write, with this source's checkpoint set to `checkpoint` (null: none). */
async function withStore(run: (store: CandidateStore, snapshotDir: string) => Promise<void>, checkpoint: string | null = 'rust-v0.162.0'): Promise<void> {
  const dir = await mkdtemp(join(tmpdir(), 'oc-files-'));
  try {
    let seconds = 0;
    const store = new CandidateStore(join(dir, 'data'), () => new Date(Date.UTC(2026, 9, 15, 0, 0, seconds++)));
    if (checkpoint) await store.setCheckpoint('lastFilesTag', checkpoint);
    await run(store, join(dir, 'snapshots'));
  } finally { await rm(dir, { recursive: true, force: true }); }
}
const snapshotPath = (snapshotDir: string, window: StableWindow) => join(snapshotDir, 'codex-files', `${window.from}__${window.to}.json`);
const readSnapshot = async (snapshotDir: string, window: StableWindow) =>
  JSON.parse(await readFile(snapshotPath(snapshotDir, window), 'utf8')) as { window: StableWindow; files: ChangedFile[] };
const byFingerprint = (candidates: Candidate[]) => [...candidates].sort((a, b) => (a.fingerprint < b.fingerprint ? -1 : 1));
const filesCandidates = async (store: CandidateStore) => byFingerprint(await store.list({ source: 'codex-files' }));
/** Nothing was stored: no candidate, no snapshot file for the window, and the checkpoint is what it was. */
async function assertNothingWritten(store: CandidateStore, snapshotDir: string, checkpoint: string | undefined = 'rust-v0.162.0', window = WINDOW): Promise<void> {
  assert.deepEqual(await store.list(), []);
  await assert.rejects(stat(snapshotPath(snapshotDir, window)), { code: 'ENOENT' });
  assert.equal(await store.checkpoint('lastFilesTag'), checkpoint);
}

